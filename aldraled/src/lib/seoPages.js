const setMeta = (selector, attr, value) => {
  let el = document.head.querySelector(selector);
  if (!el) {
    el = document.createElement('meta');
    const [, key, val] = selector.match(/\[(name|property)="([^"]+)"\]/) || [];
    if (key) el.setAttribute(key, val);
    document.head.appendChild(el);
  }
  el.setAttribute(attr, value);
};

// Titel, omschrijving en delen van de social-tags in één keer zetten
export function applySeo(title, description) {
  if (title) {
    document.title = title;
    setMeta('meta[property="og:title"]', 'content', title);
    setMeta('meta[name="twitter:title"]', 'content', title);
  }
  if (description) {
    setMeta('meta[name="description"]', 'content', description);
    setMeta('meta[property="og:description"]', 'content', description);
    setMeta('meta[name="twitter:description"]', 'content', description);
  }
}

export function seoForPath(pathname, lang) {
  const key = String(pathname || '/').replace(/^\/+|\/+$/g, '');
  const page = PAGE_SEO[key];
  if (!page) return null;
  return page[lang] || page.nl;
}
